#ifndef FKI_X86_64_ADDRESS_SPACE_COEXISTENCE_H
#define FKI_X86_64_ADDRESS_SPACE_COEXISTENCE_H

#include <linux/errno.h>

/* Validation-only layout comparison; not a pmap design or authorization. */
enum fki_x86_addrspace_item {
	FKI_X86_AS_XNU_LOW_KERNEL_VS_LINUX_INDEX511_HOLE,
	FKI_X86_AS_XNU_FULL_KERNEL_RANGE_VS_LINUX_HIGH_INDEX511,
	FKI_X86_AS_XNU_BASEMENT_VS_LINUX_ESPFIX_INDEX510,
	FKI_X86_AS_XNU_SMALL_PHYSMAP_VS_LINUX_NEIGHBORS,
	FKI_X86_AS_XNU_LARGE_PHYSMAP_VS_LINUX_CPU_ENTRY_AREA,
	FKI_X86_AS_XNU_DBLMAP_KASAN_VS_LINUX_KASAN_RANGE,
	FKI_X86_AS_KPTI_USER_CR3_ENTRY_MAPPINGS,
	FKI_X86_AS_FULL_KERNEL_CR3_COMPOSITION,
	FKI_X86_AS_PCID_TLB_NAMESPACE,
	FKI_X86_AS_ITEM_COUNT
};

enum fki_x86_addrspace_class {
	FKI_X86_AS_CLASS_DISJOINT_UNDER_CURRENT_EVIDENCE,
	FKI_X86_AS_CLASS_POTENTIAL_OVERLAP,
	FKI_X86_AS_CLASS_LAYOUT_CONFLICT_UNRESOLVED,
	FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION,
};

#define FKI_X86_AS_FLAG_PINNED_XNU_SOURCE_FACT     (1U << 0)
#define FKI_X86_AS_FLAG_LINUX_V68_DOCUMENTED_FACT  (1U << 1)
#define FKI_X86_AS_FLAG_CONDITIONAL_CONFIG         (1U << 2)
#define FKI_X86_AS_FLAG_MEMORY_SIZE_DEPENDENT      (1U << 3)
#define FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF        (1U << 4)
#define FKI_X86_AS_FLAG_KPTI_ENTRY_INPUT           (1U << 5)
#define FKI_X86_AS_FLAG_PCID_INPUT                 (1U << 6)
#define FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED       (1U << 7)
#define FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED     (1U << 8)
#define FKI_X86_AS_FLAG_NO_PRODUCTION_SAFETY       (1U << 9)

#define FKI_X86_AS_FLAG_VALID \
	(FKI_X86_AS_FLAG_PINNED_XNU_SOURCE_FACT | \
	 FKI_X86_AS_FLAG_LINUX_V68_DOCUMENTED_FACT | \
	 FKI_X86_AS_FLAG_CONDITIONAL_CONFIG | \
	 FKI_X86_AS_FLAG_MEMORY_SIZE_DEPENDENT | \
	 FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF | \
	 FKI_X86_AS_FLAG_KPTI_ENTRY_INPUT | \
	 FKI_X86_AS_FLAG_PCID_INPUT | \
	 FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED | \
	 FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED | \
	 FKI_X86_AS_FLAG_NO_PRODUCTION_SAFETY)

#define FKI_X86_AS_FACT_FLAGS \
	(FKI_X86_AS_FLAG_PINNED_XNU_SOURCE_FACT | \
	 FKI_X86_AS_FLAG_LINUX_V68_DOCUMENTED_FACT | \
	 FKI_X86_AS_FLAG_NO_PRODUCTION_SAFETY)

struct fki_x86_addrspace_entry {
	enum fki_x86_addrspace_class class;
	unsigned int flags;
};

static inline int
fki_x86_addrspace_lookup(enum fki_x86_addrspace_item item,
			 struct fki_x86_addrspace_entry *entry)
{
	if (!entry)
		return -EINVAL;
	switch (item) {
	case FKI_X86_AS_XNU_LOW_KERNEL_VS_LINUX_INDEX511_HOLE:
		entry->class = FKI_X86_AS_CLASS_DISJOINT_UNDER_CURRENT_EVIDENCE;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF;
		return 0;
	case FKI_X86_AS_XNU_FULL_KERNEL_RANGE_VS_LINUX_HIGH_INDEX511:
		entry->class = FKI_X86_AS_CLASS_LAYOUT_CONFLICT_UNRESOLVED;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED |
			FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED;
		return 0;
	case FKI_X86_AS_XNU_BASEMENT_VS_LINUX_ESPFIX_INDEX510:
		entry->class = FKI_X86_AS_CLASS_LAYOUT_CONFLICT_UNRESOLVED;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_CONDITIONAL_CONFIG |
			FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF | FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED;
		return 0;
	case FKI_X86_AS_XNU_SMALL_PHYSMAP_VS_LINUX_NEIGHBORS:
		entry->class = FKI_X86_AS_CLASS_DISJOINT_UNDER_CURRENT_EVIDENCE;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_MEMORY_SIZE_DEPENDENT |
			FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF;
		return 0;
	case FKI_X86_AS_XNU_LARGE_PHYSMAP_VS_LINUX_CPU_ENTRY_AREA:
		entry->class = FKI_X86_AS_CLASS_POTENTIAL_OVERLAP;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_MEMORY_SIZE_DEPENDENT |
			FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED;
		return 0;
	case FKI_X86_AS_XNU_DBLMAP_KASAN_VS_LINUX_KASAN_RANGE:
		entry->class = FKI_X86_AS_CLASS_POTENTIAL_OVERLAP;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_CONDITIONAL_CONFIG |
			FKI_X86_AS_FLAG_INFERENCE_NOT_PROOF | FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED;
		return 0;
	case FKI_X86_AS_KPTI_USER_CR3_ENTRY_MAPPINGS:
		entry->class = FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION;
		entry->flags = FKI_X86_AS_FLAG_LINUX_V68_DOCUMENTED_FACT |
			FKI_X86_AS_FLAG_KPTI_ENTRY_INPUT | FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED |
			FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED | FKI_X86_AS_FLAG_NO_PRODUCTION_SAFETY;
		return 0;
	case FKI_X86_AS_FULL_KERNEL_CR3_COMPOSITION:
		entry->class = FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED |
			FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED;
		return 0;
	case FKI_X86_AS_PCID_TLB_NAMESPACE:
		entry->class = FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION;
		entry->flags = FKI_X86_AS_FACT_FLAGS | FKI_X86_AS_FLAG_PCID_INPUT |
			FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED | FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED;
		return 0;
	case FKI_X86_AS_ITEM_COUNT:
		break;
	}
	return -EINVAL;
}

static inline int
fki_x86_addrspace_validate_rules(enum fki_x86_addrspace_class class,
				 unsigned int flags)
{
	if ((int)class < 0 ||
	    class > FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION ||
	    (flags & ~FKI_X86_AS_FLAG_VALID))
		return -EINVAL;
	if (!(flags & FKI_X86_AS_FLAG_NO_PRODUCTION_SAFETY))
		return -EUCLEAN;
	if (class == FKI_X86_AS_CLASS_HARD_UNRESOLVED_PROOF_OBLIGATION &&
	    (!(flags & FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED) ||
	     !(flags & FKI_X86_AS_FLAG_CR3_MEDIATION_REQUIRED)))
		return -EUCLEAN;
	if (class == FKI_X86_AS_CLASS_LAYOUT_CONFLICT_UNRESOLVED &&
	    !(flags & FKI_X86_AS_FLAG_PMAP_DESIGN_REQUIRED))
		return -EUCLEAN;
	return 0;
}

static inline int
fki_x86_addrspace_validate_entry(enum fki_x86_addrspace_item item)
{
	struct fki_x86_addrspace_entry entry;
	int ret = fki_x86_addrspace_lookup(item, &entry);

	if (ret)
		return ret;
	return fki_x86_addrspace_validate_rules(entry.class, entry.flags);
}

#endif
