#ifndef FKI_X86_64_CONTROL_MEMORY_OWNERSHIP_H
#define FKI_X86_64_CONTROL_MEMORY_OWNERSHIP_H

#include <linux/errno.h>
#include <linux/types.h>

/*
 * Validation-only ownership matrix for a possible future x86_64 XNU entry.
 * This is not an executor, state machine, loader, or ownership mechanism.
 */
enum fki_x86_control_memory_resource {
	FKI_X86_OWN_CR0,
	FKI_X86_OWN_CR3,
	FKI_X86_OWN_CR4,
	FKI_X86_OWN_EFER,
	FKI_X86_OWN_GDTR,
	FKI_X86_OWN_IDTR,
	FKI_X86_OWN_RFLAGS,
	FKI_X86_OWN_DEBUG_STATE,
	FKI_X86_OWN_SEGMENT_STATE,
	FKI_X86_OWN_XCR0,
	FKI_X86_OWN_FS_BASE,
	FKI_X86_OWN_GS_BASE,
	FKI_X86_OWN_KERNEL_GS_BASE,
	FKI_X86_OWN_CPU_IDENTITY,
	FKI_X86_OWN_TASK_IDENTITY,
	FKI_X86_OWN_PHYSICAL_RESERVATION,
	FKI_X86_OWN_HOST_MEMORY_OUTSIDE_RESERVATION,
	FKI_X86_OWN_BOOT_ARGS_CONTENT,
	FKI_X86_OWN_EFI_MAP_CONTENT,
	FKI_X86_OWN_ADT_CONTENT,
	FKI_X86_OWN_BOOT_METADATA_PLACEMENT,
	FKI_X86_OWN_BOOTSTRAP_TABLE_MEMORY,
	FKI_X86_OWN_BOOTSTRAP_REBASE_SIDE_EFFECT,
	FKI_X86_OWN_LOW_BOOT_STACK,
	FKI_X86_OWN_HIGH_BOOT_STACK,
	FKI_X86_OWN_VSTART_IDT_INIT_EFFECT,
	FKI_X86_OWN_VSTART_GS_WRITE_EFFECT,
	FKI_X86_OWN_ROLLBACK_PATH,
	FKI_X86_OWN_NMI,
	FKI_X86_OWN_IRQ,
	FKI_X86_OWN_MACHINE_CHECK,
	FKI_X86_OWN_RESOURCE_COUNT
};

enum fki_x86_control_memory_class {
	FKI_X86_OWN_CLASS_HOST_OWNED,
	FKI_X86_OWN_CLASS_FOREIGN_OWNED,
	FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
	FKI_X86_OWN_CLASS_FORBIDDEN,
	FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
};

#define FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED          (1U << 0)
#define FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL (1U << 1)
#define FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED      (1U << 2)
#define FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT       (1U << 3)
#define FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD        (1U << 4)
#define FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED       (1U << 5)
#define FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING       (1U << 6)
#define FKI_X86_OWN_FLAG_NO_FOREIGN_ACCESS          (1U << 7)

#define FKI_X86_OWN_FLAG_VALID \
	(FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED | \
	 FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL | \
	 FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED | \
	 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT | \
	 FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD | \
	 FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED | \
	 FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING | \
	 FKI_X86_OWN_FLAG_NO_FOREIGN_ACCESS)

static inline int
fki_x86_control_memory_ownership_lookup(enum fki_x86_control_memory_resource resource,
					 enum fki_x86_control_memory_class *class,
					 unsigned int *flags)
{
	if (!class || !flags)
		return -EINVAL;

	switch (resource) {
	case FKI_X86_OWN_CR0:
	case FKI_X86_OWN_CR3:
	case FKI_X86_OWN_CR4:
	case FKI_X86_OWN_EFER:
	case FKI_X86_OWN_GDTR:
	case FKI_X86_OWN_IDTR:
	case FKI_X86_OWN_RFLAGS:
	case FKI_X86_OWN_DEBUG_STATE:
	case FKI_X86_OWN_SEGMENT_STATE:
	case FKI_X86_OWN_XCR0:
	case FKI_X86_OWN_FS_BASE:
	case FKI_X86_OWN_KERNEL_GS_BASE:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT;
		return 0;
	case FKI_X86_OWN_GS_BASE:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT |
			 FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD;
		return 0;
	case FKI_X86_OWN_CPU_IDENTITY:
	case FKI_X86_OWN_TASK_IDENTITY:
		*class = FKI_X86_OWN_CLASS_HOST_OWNED;
		*flags = 0;
		return 0;
	case FKI_X86_OWN_PHYSICAL_RESERVATION:
	case FKI_X86_OWN_BOOT_ARGS_CONTENT:
	case FKI_X86_OWN_EFI_MAP_CONTENT:
	case FKI_X86_OWN_ADT_CONTENT:
		*class = FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED;
		*flags = FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT |
			 FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING;
		return 0;
	case FKI_X86_OWN_HOST_MEMORY_OUTSIDE_RESERVATION:
		*class = FKI_X86_OWN_CLASS_FORBIDDEN;
		*flags = FKI_X86_OWN_FLAG_NO_FOREIGN_ACCESS;
		return 0;
	case FKI_X86_OWN_BOOT_METADATA_PLACEMENT:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED;
		return 0;
	case FKI_X86_OWN_BOOTSTRAP_TABLE_MEMORY:
	case FKI_X86_OWN_LOW_BOOT_STACK:
	case FKI_X86_OWN_HIGH_BOOT_STACK:
		*class = FKI_X86_OWN_CLASS_FOREIGN_OWNED;
		*flags = FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT |
			 FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING;
		return 0;
	case FKI_X86_OWN_BOOTSTRAP_REBASE_SIDE_EFFECT:
	case FKI_X86_OWN_ROLLBACK_PATH:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT;
		return 0;
	case FKI_X86_OWN_VSTART_IDT_INIT_EFFECT:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT |
			 FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD;
		return 0;
	case FKI_X86_OWN_VSTART_GS_WRITE_EFFECT:
		*class = FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
			 FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT |
			 FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD;
		return 0;
	case FKI_X86_OWN_NMI:
	case FKI_X86_OWN_IRQ:
	case FKI_X86_OWN_MACHINE_CHECK:
		*class = FKI_X86_OWN_CLASS_FORBIDDEN;
		*flags = FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED |
			 FKI_X86_OWN_FLAG_NO_FOREIGN_ACCESS;
		return 0;
	case FKI_X86_OWN_RESOURCE_COUNT:
		break;
	}
	return -EINVAL;
}

static inline int
fki_x86_control_memory_ownership_validate_rules(enum fki_x86_control_memory_class class,
						 unsigned int flags)
{
	if ((int)class < 0 || class > FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL ||
	    (flags & ~FKI_X86_OWN_FLAG_VALID))
		return -EINVAL;
	if (class == FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL &&
	    !(flags & FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL))
		return -EUCLEAN;
	if ((class == FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED ||
	     class == FKI_X86_OWN_CLASS_FOREIGN_OWNED) &&
	    !(flags & FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED))
		return -EUCLEAN;
	if ((flags & FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED) &&
	    class != FKI_X86_OWN_CLASS_FORBIDDEN)
		return -EUCLEAN;
	if ((flags & (FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD |
		       FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED)) &&
	    class != FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL)
		return -EUCLEAN;
	if (class == FKI_X86_OWN_CLASS_FORBIDDEN &&
	    (flags & FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED))
		return -EUCLEAN;
	return 0;
}

static inline int
fki_x86_control_memory_ownership_validate_entry(enum fki_x86_control_memory_resource resource)
{
	enum fki_x86_control_memory_class class;
	unsigned int flags;
	int ret = fki_x86_control_memory_ownership_lookup(resource, &class, &flags);

	if (ret)
		return ret;
	return fki_x86_control_memory_ownership_validate_rules(class, flags);
}

#endif
