#ifndef FKI_X86_64_COOPERATIVE_HANDOFF_OBLIGATIONS_H
#define FKI_X86_64_COOPERATIVE_HANDOFF_OBLIGATIONS_H

#include <linux/errno.h>

/*
 * Validation-only x86 cooperative-handoff proof obligations. This is not a
 * route selection, patch design, ABI, handoff contract, or authorization to
 * execute foreign code.
 */
enum fki_x86_coop_obligation {
	FKI_X86_COOP_CR3_KPTI_PCID_ADDRESS_SPACE_SPLIT,
	FKI_X86_COOP_GS_SWAPGS_CPU_DATA_CONFLICT,
	FKI_X86_COOP_SYSCALL_MSR_STAR_LSTAR_SFMASK,
	FKI_X86_COOP_CONTROL_REGISTER_MEDIATION,
	FKI_X86_COOP_LAPIC_TPR_IPI_COEXISTENCE,
	FKI_X86_COOP_TSS_IST_STACK_OWNERSHIP,
	FKI_X86_COOP_XSAVE_AVX_FPU_STATE,
	FKI_X86_COOP_PHYSICAL_MEMORY_RESERVATION,
	FKI_X86_COOP_PMAP_ADDRESS_SPACE_INTEGRATION,
	FKI_X86_COOP_EXCEPTION_ENTRY_FORWARDING,
	FKI_X86_COOP_INTERRUPT_PREEMPTION_COEXISTENCE,
	FKI_X86_COOP_ROLLBACK_CLEANUP,
	FKI_X86_COOP_OBLIGATION_COUNT
};

enum fki_x86_coop_obligation_class {
	FKI_X86_COOP_CLASS_STRUCTURAL_MISMATCH,
	FKI_X86_COOP_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
	FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED,
	FKI_X86_COOP_CLASS_FORBIDDEN_AS_CURRENT_CLAIM,
};

#define FKI_X86_COOP_FLAG_ARM64_ANALOGY_INSUFFICIENT      (1U << 0)
#define FKI_X86_COOP_FLAG_REQUIRES_XNU_PATCH_OR_CONTRACT       (1U << 1)
#define FKI_X86_COOP_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED    (1U << 2)
#define FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT      (1U << 3)
#define FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT                  (1U << 4)
#define FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT               (1U << 5)
#define FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT            (1U << 6)
#define FKI_X86_COOP_FLAG_USER_STATE_CONTEXT_INPUT             (1U << 7)
#define FKI_X86_COOP_FLAG_ROLLBACK_INPUT                       (1U << 8)
#define FKI_X86_COOP_FLAG_PRODUCTION_SAFETY_UNPROVEN           (1U << 9)

#define FKI_X86_COOP_FLAG_VALID \
	(FKI_X86_COOP_FLAG_ARM64_ANALOGY_INSUFFICIENT | \
	 FKI_X86_COOP_FLAG_REQUIRES_XNU_PATCH_OR_CONTRACT | \
	 FKI_X86_COOP_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED | \
	 FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT | \
	 FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT | \
	 FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT | \
	 FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT | \
	 FKI_X86_COOP_FLAG_USER_STATE_CONTEXT_INPUT | \
	 FKI_X86_COOP_FLAG_ROLLBACK_INPUT | \
	 FKI_X86_COOP_FLAG_PRODUCTION_SAFETY_UNPROVEN)

#define FKI_X86_COOP_COMMON_FLAGS \
	(FKI_X86_COOP_FLAG_ARM64_ANALOGY_INSUFFICIENT | \
	 FKI_X86_COOP_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED | \
	 FKI_X86_COOP_FLAG_PRODUCTION_SAFETY_UNPROVEN)

struct fki_x86_coop_obligation_entry {
	enum fki_x86_coop_obligation_class class;
	unsigned int flags;
};

static inline int
fki_x86_coop_obligation_lookup(enum fki_x86_coop_obligation obligation,
			       struct fki_x86_coop_obligation_entry *entry)
{
	if (!entry)
		return -EINVAL;

	switch (obligation) {
	case FKI_X86_COOP_CR3_KPTI_PCID_ADDRESS_SPACE_SPLIT:
		entry->class = FKI_X86_COOP_CLASS_STRUCTURAL_MISMATCH;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
			FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT;
		return 0;
	case FKI_X86_COOP_GS_SWAPGS_CPU_DATA_CONFLICT:
		entry->class = FKI_X86_COOP_CLASS_STRUCTURAL_MISMATCH;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
			FKI_X86_COOP_FLAG_REQUIRES_XNU_PATCH_OR_CONTRACT;
		return 0;
	case FKI_X86_COOP_SYSCALL_MSR_STAR_LSTAR_SFMASK:
		entry->class = FKI_X86_COOP_CLASS_FORBIDDEN_AS_CURRENT_CLAIM;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
			FKI_X86_COOP_FLAG_REQUIRES_XNU_PATCH_OR_CONTRACT;
		return 0;
	case FKI_X86_COOP_CONTROL_REGISTER_MEDIATION:
		entry->class = FKI_X86_COOP_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT;
		return 0;
	case FKI_X86_COOP_LAPIC_TPR_IPI_COEXISTENCE:
		entry->class = FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
			FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT;
		return 0;
	case FKI_X86_COOP_TSS_IST_STACK_OWNERSHIP:
		entry->class = FKI_X86_COOP_CLASS_STRUCTURAL_MISMATCH;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
			FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT;
		return 0;
	case FKI_X86_COOP_XSAVE_AVX_FPU_STATE:
		entry->class = FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_USER_STATE_CONTEXT_INPUT;
		return 0;
	case FKI_X86_COOP_PHYSICAL_MEMORY_RESERVATION:
		entry->class = FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT;
		return 0;
	case FKI_X86_COOP_PMAP_ADDRESS_SPACE_INTEGRATION:
		entry->class = FKI_X86_COOP_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT |
			FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT;
		return 0;
	case FKI_X86_COOP_EXCEPTION_ENTRY_FORWARDING:
		entry->class = FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT |
			FKI_X86_COOP_FLAG_REQUIRES_XNU_PATCH_OR_CONTRACT;
		return 0;
	case FKI_X86_COOP_INTERRUPT_PREEMPTION_COEXISTENCE:
		entry->class = FKI_X86_COOP_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT;
		return 0;
	case FKI_X86_COOP_ROLLBACK_CLEANUP:
		entry->class = FKI_X86_COOP_CLASS_REQUIRED_BUT_UNDESIGNED;
		entry->flags = FKI_X86_COOP_COMMON_FLAGS |
			FKI_X86_COOP_FLAG_ROLLBACK_INPUT;
		return 0;
	case FKI_X86_COOP_OBLIGATION_COUNT:
		break;
	}
	return -EINVAL;
}

static inline int
fki_x86_coop_validate_rules(enum fki_x86_coop_obligation_class class,
			    unsigned int flags)
{
	unsigned int domain_flags = FKI_X86_COOP_FLAG_CONTROL_STATE_INPUT |
		FKI_X86_COOP_FLAG_MEMORY_OWNERSHIP_INPUT |
		FKI_X86_COOP_FLAG_EXCEPTION_INTERRUPT_INPUT |
		FKI_X86_COOP_FLAG_USER_STATE_CONTEXT_INPUT |
		FKI_X86_COOP_FLAG_ROLLBACK_INPUT;

	if ((int)class < 0 ||
	    class > FKI_X86_COOP_CLASS_FORBIDDEN_AS_CURRENT_CLAIM ||
	    (flags & ~FKI_X86_COOP_FLAG_VALID))
		return -EINVAL;
	if ((flags & FKI_X86_COOP_COMMON_FLAGS) != FKI_X86_COOP_COMMON_FLAGS)
		return -EUCLEAN;
	if (!(flags & domain_flags))
		return -EUCLEAN;
	if (class == FKI_X86_COOP_CLASS_STRUCTURAL_MISMATCH &&
	    !(flags & FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT))
		return -EUCLEAN;
	if (class == FKI_X86_COOP_CLASS_FORBIDDEN_AS_CURRENT_CLAIM &&
	    !(flags & FKI_X86_COOP_FLAG_SHARED_SINGLE_RESOURCE_CONFLICT))
		return -EUCLEAN;
	return 0;
}

static inline int
fki_x86_coop_obligation_validate_entry(enum fki_x86_coop_obligation obligation)
{
	struct fki_x86_coop_obligation_entry entry;
	int ret = fki_x86_coop_obligation_lookup(obligation, &entry);

	if (ret)
		return ret;
	return fki_x86_coop_validate_rules(entry.class, entry.flags);
}

#endif
