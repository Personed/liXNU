#ifndef FKI_X86_64_CPU_QUIESCENCE_DECISION_H
#define FKI_X86_64_CPU_QUIESCENCE_DECISION_H

#include <linux/errno.h>

/*
 * Validation-only CPU-quiescence decision record. This is not a runtime
 * mechanism and does not authorize foreign control-state transfer.
 */
enum fki_x86_cpu_quiescence_route {
	FKI_X86_QUIESCENCE_LIVE_LINUX_CPU,
	FKI_X86_QUIESCENCE_STOP_MACHINE,
	FKI_X86_QUIESCENCE_LOGICAL_OFFLINE_HOTPLUG,
	FKI_X86_QUIESCENCE_ROLLBACK_REONLINE,
	FKI_X86_QUIESCENCE_ROUTE_COUNT
};

enum fki_x86_cpu_quiescence_class {
	FKI_X86_QUIESCENCE_CLASS_FORBIDDEN_PRODUCTION,
	FKI_X86_QUIESCENCE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
	FKI_X86_QUIESCENCE_CLASS_POTENTIALLY_NECESSARY_BUT_INSUFFICIENT,
};

#define FKI_X86_QUIESCENCE_FLAG_TEMPORARY_ONLY                    (1U << 0)
#define FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER             (1U << 1)
#define FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED          (1U << 2)
#define FKI_X86_QUIESCENCE_FLAG_NMI_UNSUPPORTED                   (1U << 3)
#define FKI_X86_QUIESCENCE_FLAG_IRQ_UNSUPPORTED                   (1U << 4)
#define FKI_X86_QUIESCENCE_FLAG_MACHINE_CHECK_UNSUPPORTED         (1U << 5)
#define FKI_X86_QUIESCENCE_FLAG_REONLINE_WAKE_RESET_UNDECIDED     (1U << 6)
#define FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE            (1U << 7)
#define FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE                (1U << 8)
#define FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL        (1U << 9)

#define FKI_X86_QUIESCENCE_FLAG_VALID \
	(FKI_X86_QUIESCENCE_FLAG_TEMPORARY_ONLY | \
	 FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER | \
	 FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED | \
	 FKI_X86_QUIESCENCE_FLAG_NMI_UNSUPPORTED | \
	 FKI_X86_QUIESCENCE_FLAG_IRQ_UNSUPPORTED | \
	 FKI_X86_QUIESCENCE_FLAG_MACHINE_CHECK_UNSUPPORTED | \
	 FKI_X86_QUIESCENCE_FLAG_REONLINE_WAKE_RESET_UNDECIDED | \
	 FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE | \
	 FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE | \
	 FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL)

#define FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED \
	(FKI_X86_QUIESCENCE_FLAG_NMI_UNSUPPORTED | \
	 FKI_X86_QUIESCENCE_FLAG_IRQ_UNSUPPORTED | \
	 FKI_X86_QUIESCENCE_FLAG_MACHINE_CHECK_UNSUPPORTED)

static inline int
fki_x86_cpu_quiescence_lookup(enum fki_x86_cpu_quiescence_route route,
			      enum fki_x86_cpu_quiescence_class *class,
			      unsigned int *flags)
{
	if (!class || !flags)
		return -EINVAL;

	switch (route) {
	case FKI_X86_QUIESCENCE_LIVE_LINUX_CPU:
		*class = FKI_X86_QUIESCENCE_CLASS_FORBIDDEN_PRODUCTION;
		*flags = FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER |
			 FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED |
			 FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED |
			 FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE;
		return 0;
	case FKI_X86_QUIESCENCE_STOP_MACHINE:
		*class = FKI_X86_QUIESCENCE_CLASS_POTENTIALLY_NECESSARY_BUT_INSUFFICIENT;
		*flags = FKI_X86_QUIESCENCE_FLAG_TEMPORARY_ONLY |
			 FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER |
			 FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED |
			 FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED |
			 FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE |
			 FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE |
			 FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL;
		return 0;
	case FKI_X86_QUIESCENCE_LOGICAL_OFFLINE_HOTPLUG:
		*class = FKI_X86_QUIESCENCE_CLASS_POTENTIALLY_NECESSARY_BUT_INSUFFICIENT;
		*flags = FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER |
			 FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED |
			 FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED |
			 FKI_X86_QUIESCENCE_FLAG_REONLINE_WAKE_RESET_UNDECIDED |
			 FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE |
			 FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE |
			 FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL;
		return 0;
	case FKI_X86_QUIESCENCE_ROLLBACK_REONLINE:
		*class = FKI_X86_QUIESCENCE_CLASS_UNRESOLVED_STRONGER_PROTOCOL;
		*flags = FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER |
			 FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED |
			 FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED |
			 FKI_X86_QUIESCENCE_FLAG_REONLINE_WAKE_RESET_UNDECIDED |
			 FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE |
			 FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL;
		return 0;
	case FKI_X86_QUIESCENCE_ROUTE_COUNT:
		break;
	}
	return -EINVAL;
}

static inline int
fki_x86_cpu_quiescence_validate_rules(enum fki_x86_cpu_quiescence_class class,
				      unsigned int flags)
{
	if ((int)class < 0 ||
	    class > FKI_X86_QUIESCENCE_CLASS_POTENTIALLY_NECESSARY_BUT_INSUFFICIENT ||
	    (flags & ~FKI_X86_QUIESCENCE_FLAG_VALID))
		return -EINVAL;
	if (class == FKI_X86_QUIESCENCE_CLASS_UNRESOLVED_STRONGER_PROTOCOL &&
	    !(flags & FKI_X86_QUIESCENCE_FLAG_REQUIRES_STRONGER_PROTOCOL))
		return -EUCLEAN;
	if (class == FKI_X86_QUIESCENCE_CLASS_POTENTIALLY_NECESSARY_BUT_INSUFFICIENT &&
	    (!(flags & FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE) ||
	     !(flags & FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE)))
		return -EUCLEAN;
	if (class == FKI_X86_QUIESCENCE_CLASS_FORBIDDEN_PRODUCTION &&
	    (flags & FKI_X86_QUIESCENCE_FLAG_POTENTIAL_PREREQUISITE))
		return -EUCLEAN;
	if ((flags & FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED) !=
	    FKI_X86_QUIESCENCE_ASYNC_UNSUPPORTED)
		return -EUCLEAN;
	if (!(flags & FKI_X86_QUIESCENCE_FLAG_NO_OWNERSHIP_TRANSFER) ||
	    !(flags & FKI_X86_QUIESCENCE_FLAG_CONTROL_MEMORY_UNDECIDED) ||
	    !(flags & FKI_X86_QUIESCENCE_FLAG_INSUFFICIENT_ALONE))
		return -EUCLEAN;
	return 0;
}

static inline int
fki_x86_cpu_quiescence_validate_entry(enum fki_x86_cpu_quiescence_route route)
{
	enum fki_x86_cpu_quiescence_class class;
	unsigned int flags;
	int ret = fki_x86_cpu_quiescence_lookup(route, &class, &flags);

	if (ret)
		return ret;
	return fki_x86_cpu_quiescence_validate_rules(class, flags);
}

#endif
