#ifndef FKI_X86_64_ENTRY_ARCHITECTURE_DECISION_H
#define FKI_X86_64_ENTRY_ARCHITECTURE_DECISION_H

#include <linux/errno.h>

/*
 * Validation-only entry-architecture decision matrix. This is not a route,
 * protocol, executor, ABI, or authorization to enter foreign code.
 */
enum fki_x86_entry_architecture_route {
	FKI_X86_ENTRY_ARCH_PROTECTED_UNMODIFIED_PHYSICAL_CPU,
	FKI_X86_ENTRY_ARCH_INIT_SIPI_MANUAL_OFFLINE_INJECTION,
	FKI_X86_ENTRY_ARCH_COOPERATIVE_PATCHED_LINUX_OWNERSHIP,
	FKI_X86_ENTRY_ARCH_ROUTE_COUNT
};

enum fki_x86_entry_architecture_class {
	FKI_X86_ENTRY_ARCH_BLOCKED_UNRESOLVED_INJECTION_OWNERSHIP,
	FKI_X86_ENTRY_ARCH_UNRESOLVED_NOT_BLOCKED_BY_INJECTION_GAP,
};

#define FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION      (1U << 0)
#define FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP              (1U << 1)
#define FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_MODULE_API_OR_KERNEL_COOP    (1U << 2)
#define FKI_X86_ENTRY_ARCH_FLAG_INIT_SIPI_REIMPLEMENTATION_FORBIDDEN  (1U << 3)
#define FKI_X86_ENTRY_ARCH_FLAG_AVOIDS_PHYSICAL_CPU_POSSESSION        (1U << 4)
#define FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_XNU_PATCH                    (1U << 5)
#define FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_ABI_HANDOFF_CONTRACT         (1U << 6)
#define FKI_X86_ENTRY_ARCH_FLAG_MEMORY_OWNERSHIP_UNRESOLVED           (1U << 7)
#define FKI_X86_ENTRY_ARCH_FLAG_CONTROL_STATE_UNRESOLVED              (1U << 8)
#define FKI_X86_ENTRY_ARCH_FLAG_EXCEPTION_SYSCALL_UNRESOLVED          (1U << 9)
#define FKI_X86_ENTRY_ARCH_FLAG_ROLLBACK_UNRESOLVED                   (1U << 10)
#define FKI_X86_ENTRY_ARCH_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED     (1U << 11)
#define FKI_X86_ENTRY_ARCH_FLAG_ARM64_ANALOGY_ONLY                    (1U << 12)
#define FKI_X86_ENTRY_ARCH_FLAG_XNU_PREBOOT_LONG_NOT_VALIDATED        (1U << 13)

#define FKI_X86_ENTRY_ARCH_FLAG_VALID \
	(FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION | \
	 FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP | \
	 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_MODULE_API_OR_KERNEL_COOP | \
	 FKI_X86_ENTRY_ARCH_FLAG_INIT_SIPI_REIMPLEMENTATION_FORBIDDEN | \
	 FKI_X86_ENTRY_ARCH_FLAG_AVOIDS_PHYSICAL_CPU_POSSESSION | \
	 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_XNU_PATCH | \
	 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_ABI_HANDOFF_CONTRACT | \
	 FKI_X86_ENTRY_ARCH_FLAG_MEMORY_OWNERSHIP_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_CONTROL_STATE_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_EXCEPTION_SYSCALL_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_ROLLBACK_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_ARM64_ANALOGY_ONLY | \
	 FKI_X86_ENTRY_ARCH_FLAG_XNU_PREBOOT_LONG_NOT_VALIDATED)

#define FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED \
	(FKI_X86_ENTRY_ARCH_FLAG_MEMORY_OWNERSHIP_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_CONTROL_STATE_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_EXCEPTION_SYSCALL_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_ROLLBACK_UNRESOLVED | \
	 FKI_X86_ENTRY_ARCH_FLAG_LINUX_OWNERSHIP_MUST_BE_PRESERVED)

static inline int
fki_x86_entry_architecture_lookup(enum fki_x86_entry_architecture_route route,
				  enum fki_x86_entry_architecture_class *class,
				  unsigned int *flags)
{
	if (!class || !flags)
		return -EINVAL;

	switch (route) {
	case FKI_X86_ENTRY_ARCH_PROTECTED_UNMODIFIED_PHYSICAL_CPU:
		*class = FKI_X86_ENTRY_ARCH_BLOCKED_UNRESOLVED_INJECTION_OWNERSHIP;
		*flags = FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION |
			 FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP |
			 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_MODULE_API_OR_KERNEL_COOP |
			 FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED;
		return 0;
	case FKI_X86_ENTRY_ARCH_INIT_SIPI_MANUAL_OFFLINE_INJECTION:
		*class = FKI_X86_ENTRY_ARCH_BLOCKED_UNRESOLVED_INJECTION_OWNERSHIP;
		*flags = FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION |
			 FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP |
			 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_MODULE_API_OR_KERNEL_COOP |
			 FKI_X86_ENTRY_ARCH_FLAG_INIT_SIPI_REIMPLEMENTATION_FORBIDDEN |
			 FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED;
		return 0;
	case FKI_X86_ENTRY_ARCH_COOPERATIVE_PATCHED_LINUX_OWNERSHIP:
		*class = FKI_X86_ENTRY_ARCH_UNRESOLVED_NOT_BLOCKED_BY_INJECTION_GAP;
		*flags = FKI_X86_ENTRY_ARCH_FLAG_AVOIDS_PHYSICAL_CPU_POSSESSION |
			 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_XNU_PATCH |
			 FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_ABI_HANDOFF_CONTRACT |
			 FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED |
			 FKI_X86_ENTRY_ARCH_FLAG_ARM64_ANALOGY_ONLY |
			 FKI_X86_ENTRY_ARCH_FLAG_XNU_PREBOOT_LONG_NOT_VALIDATED;
		return 0;
	case FKI_X86_ENTRY_ARCH_ROUTE_COUNT:
		break;
	}
	return -EINVAL;
}

static inline int
fki_x86_entry_architecture_validate_rules(enum fki_x86_entry_architecture_class class,
					  unsigned int flags)
{
	if ((int)class < 0 ||
	    class > FKI_X86_ENTRY_ARCH_UNRESOLVED_NOT_BLOCKED_BY_INJECTION_GAP ||
	    (flags & ~FKI_X86_ENTRY_ARCH_FLAG_VALID))
		return -EINVAL;
	if (class == FKI_X86_ENTRY_ARCH_BLOCKED_UNRESOLVED_INJECTION_OWNERSHIP &&
	    (!(flags & FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_MODULE_API_OR_KERNEL_COOP)))
		return -EUCLEAN;
	if (class == FKI_X86_ENTRY_ARCH_UNRESOLVED_NOT_BLOCKED_BY_INJECTION_GAP &&
	    (!(flags & FKI_X86_ENTRY_ARCH_FLAG_AVOIDS_PHYSICAL_CPU_POSSESSION) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_XNU_PATCH) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_ABI_HANDOFF_CONTRACT) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_ARM64_ANALOGY_ONLY) ||
	     !(flags & FKI_X86_ENTRY_ARCH_FLAG_XNU_PREBOOT_LONG_NOT_VALIDATED)))
		return -EUCLEAN;
	if ((flags & FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED) !=
	    FKI_X86_ENTRY_ARCH_COMMON_UNRESOLVED)
		return -EUCLEAN;
	if ((flags & FKI_X86_ENTRY_ARCH_FLAG_AVOIDS_PHYSICAL_CPU_POSSESSION) &&
	    (flags & FKI_X86_ENTRY_ARCH_FLAG_REQUIRES_PHYSICAL_CPU_POSSESSION))
		return -EUCLEAN;
	if (class == FKI_X86_ENTRY_ARCH_UNRESOLVED_NOT_BLOCKED_BY_INJECTION_GAP &&
	    (flags & FKI_X86_ENTRY_ARCH_FLAG_BLOCKED_BY_INJECTION_GAP))
		return -EUCLEAN;
	return 0;
}

static inline int
fki_x86_entry_architecture_validate_entry(enum fki_x86_entry_architecture_route route)
{
	enum fki_x86_entry_architecture_class class;
	unsigned int flags;
	int ret = fki_x86_entry_architecture_lookup(route, &class, &flags);

	if (ret)
		return ret;
	return fki_x86_entry_architecture_validate_rules(class, flags);
}

#endif
