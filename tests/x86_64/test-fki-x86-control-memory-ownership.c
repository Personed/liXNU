#include <assert.h>
#include <errno.h>
#include <stdio.h>

#include "../../fki-ko/fki_x86_64_control_memory_ownership.h"

static void expect_entry(enum fki_x86_control_memory_resource resource,
			 enum fki_x86_control_memory_class expected_class,
			 unsigned int required_flags)
{
	enum fki_x86_control_memory_class class;
	unsigned int flags;

	assert(fki_x86_control_memory_ownership_lookup(resource, &class, &flags) == 0);
	assert(class == expected_class);
	assert((flags & required_flags) == required_flags);
	assert(fki_x86_control_memory_ownership_validate_entry(resource) == 0);
}

int main(void)
{
	unsigned int resource;

	for (resource = 0; resource < FKI_X86_OWN_RESOURCE_COUNT; resource++)
		assert(fki_x86_control_memory_ownership_validate_entry(resource) == 0);
	assert(fki_x86_control_memory_ownership_validate_entry(FKI_X86_OWN_RESOURCE_COUNT) == -EINVAL);

	expect_entry(FKI_X86_OWN_CR0, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL |
		     FKI_X86_OWN_FLAG_ROLLBACK_SIDE_EFFECT);
	expect_entry(FKI_X86_OWN_CR3, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_CR4, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_EFER, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_GDTR, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_IDTR, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_RFLAGS, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_DEBUG_STATE, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_SEGMENT_STATE, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_XCR0, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_FS_BASE, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_GS_BASE, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD);
	expect_entry(FKI_X86_OWN_KERNEL_GS_BASE, FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OWN_CPU_IDENTITY, FKI_X86_OWN_CLASS_HOST_OWNED, 0);
	expect_entry(FKI_X86_OWN_TASK_IDENTITY, FKI_X86_OWN_CLASS_HOST_OWNED, 0);

	expect_entry(FKI_X86_OWN_PHYSICAL_RESERVATION,
		     FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
		     FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED |
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_HOST_MEMORY_OUTSIDE_RESERVATION,
		     FKI_X86_OWN_CLASS_FORBIDDEN,
		     FKI_X86_OWN_FLAG_NO_FOREIGN_ACCESS);
	expect_entry(FKI_X86_OWN_BOOT_ARGS_CONTENT,
		     FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_EFI_MAP_CONTENT,
		     FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_ADT_CONTENT,
		     FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_BOOT_METADATA_PLACEMENT,
		     FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED);
	expect_entry(FKI_X86_OWN_BOOTSTRAP_TABLE_MEMORY,
		     FKI_X86_OWN_CLASS_FOREIGN_OWNED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_BOOTSTRAP_REBASE_SIDE_EFFECT,
		     FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED);
	expect_entry(FKI_X86_OWN_LOW_BOOT_STACK, FKI_X86_OWN_CLASS_FOREIGN_OWNED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_HIGH_BOOT_STACK, FKI_X86_OWN_CLASS_FOREIGN_OWNED,
		     FKI_X86_OWN_FLAG_HOST_RETAINS_BACKING);
	expect_entry(FKI_X86_OWN_VSTART_IDT_INIT_EFFECT,
		     FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD);
	expect_entry(FKI_X86_OWN_VSTART_GS_WRITE_EFFECT,
		     FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_BEFORE_MEMORY_GUARD);
	expect_entry(FKI_X86_OWN_ROLLBACK_PATH,
		     FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED);
	expect_entry(FKI_X86_OWN_NMI, FKI_X86_OWN_CLASS_FORBIDDEN,
		     FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED);
	expect_entry(FKI_X86_OWN_IRQ, FKI_X86_OWN_CLASS_FORBIDDEN,
		     FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED);
	expect_entry(FKI_X86_OWN_MACHINE_CHECK, FKI_X86_OWN_CLASS_FORBIDDEN,
		     FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED);

	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_UNRESOLVED_STRONGER_PROTOCOL, 0) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED, 0) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_FOREIGN_OWNED, 0) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_HOST_OWNED,
		FKI_X86_OWN_FLAG_ASYNC_UNSUPPORTED) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_TEMPORARILY_TRANSFERRED,
		FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED |
		FKI_X86_OWN_FLAG_PLACEMENT_UNRESOLVED) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_FORBIDDEN,
		FKI_X86_OWN_FLAG_EXACTLY_ONCE_REQUIRED) == -EUCLEAN);
	assert(fki_x86_control_memory_ownership_validate_rules(
		FKI_X86_OWN_CLASS_HOST_OWNED, ~0U) == -EINVAL);

	puts("x86 control/memory ownership matrix fixtures passed");
	return 0;
}
