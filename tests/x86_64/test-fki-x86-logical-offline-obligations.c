#include <assert.h>
#include <stdio.h>

#include "../../fki-ko/fki_x86_64_logical_offline_obligations.h"

static void expect_entry(enum fki_x86_offline_obligation obligation,
			 enum fki_x86_offline_obligation_class expected_class,
			 unsigned int expected_flags)
{
	enum fki_x86_offline_obligation_class class;
	unsigned int flags;

	assert(fki_x86_offline_obligation_lookup(obligation, &class, &flags) == 0);
	assert(class == expected_class);
	assert(flags == expected_flags);
	assert(fki_x86_offline_obligation_validate_entry(obligation) == 0);
}

int main(void)
{
	enum fki_x86_offline_obligation_class class;
	unsigned int flags;
	unsigned int primitive = FKI_X86_OFFLINE_FLAG_EXPORTED_SYMBOL_EVIDENCE |
		FKI_X86_OFFLINE_FLAG_NO_PHYSICAL_CPU_OWNERSHIP |
		FKI_X86_OFFLINE_FLAG_NO_MEMORY_CONTROL_OWNERSHIP |
		FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL;
	unsigned int claim = FKI_X86_OFFLINE_FLAG_NO_PHYSICAL_CPU_OWNERSHIP |
		FKI_X86_OFFLINE_FLAG_NO_MEMORY_CONTROL_OWNERSHIP |
		FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL;
	enum fki_x86_offline_obligation obligation;

	for (obligation = 0; obligation < FKI_X86_OFFLINE_OBLIGATION_COUNT; obligation++)
		assert(fki_x86_offline_obligation_validate_entry(obligation) == 0);

	expect_entry(FKI_X86_OFFLINE_STOP_MACHINE_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		     primitive | FKI_X86_OFFLINE_FLAG_TEMPORARY_OR_LOCKING_ONLY);
	expect_entry(FKI_X86_OFFLINE_REMOVE_CPU_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		     primitive | FKI_X86_OFFLINE_FLAG_SERIALIZES_LOGICAL_HOTPLUG);
	expect_entry(FKI_X86_OFFLINE_ADD_CPU_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		     primitive | FKI_X86_OFFLINE_FLAG_SERIALIZES_LOGICAL_HOTPLUG |
		     FKI_X86_OFFLINE_FLAG_REONLINE_CONTROL_UNDECIDED);
	expect_entry(FKI_X86_OFFLINE_CPU_HOTPLUG_DISABLE_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		     primitive | FKI_X86_OFFLINE_FLAG_SERIALIZES_LOGICAL_HOTPLUG |
		     FKI_X86_OFFLINE_FLAG_GLOBAL_SIDE_EFFECT);
	expect_entry(FKI_X86_OFFLINE_CPUHP_CALLBACK_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_EVIDENCE_ONLY_PRIMITIVE, primitive);
	expect_entry(FKI_X86_OFFLINE_CPUS_READ_LOCK_PRIMITIVE,
		     FKI_X86_OFFLINE_CLASS_EVIDENCE_ONLY_PRIMITIVE,
		     primitive | FKI_X86_OFFLINE_FLAG_TEMPORARY_OR_LOCKING_ONLY);
	expect_entry(FKI_X86_OFFLINE_STOP_MACHINE_OWNERSHIP_CLAIM,
		     FKI_X86_OFFLINE_CLASS_FORBIDDEN_AS_OWNERSHIP_CLAIM, claim);
	expect_entry(FKI_X86_OFFLINE_LOGICAL_OFFLINE_OWNERSHIP_CLAIM,
		     FKI_X86_OFFLINE_CLASS_FORBIDDEN_AS_OWNERSHIP_CLAIM, claim);
	expect_entry(FKI_X86_OFFLINE_HOTPLUG_BLOCK_OWNERSHIP_CLAIM,
		     FKI_X86_OFFLINE_CLASS_FORBIDDEN_AS_OWNERSHIP_CLAIM, claim);
	expect_entry(FKI_X86_OFFLINE_COMBINED_OFFLINE_AND_BLOCKING,
		     FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		     primitive | FKI_X86_OFFLINE_FLAG_SERIALIZES_LOGICAL_HOTPLUG |
		     FKI_X86_OFFLINE_FLAG_GLOBAL_SIDE_EFFECT |
		     FKI_X86_OFFLINE_FLAG_WAKE_RESET_UNDECIDED |
		     FKI_X86_OFFLINE_FLAG_REONLINE_CONTROL_UNDECIDED |
		     FKI_X86_OFFLINE_FLAG_ROLLBACK_UNDESIGNED);
	expect_entry(FKI_X86_OFFLINE_MEMORY_OWNERSHIP,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_NO_MEMORY_CONTROL_OWNERSHIP |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_CPU_SELECTION_PHYSICAL_POSSESSION,
		     FKI_X86_OFFLINE_CLASS_REQUIRED_BUT_UNDESIGNED,
		     FKI_X86_OFFLINE_FLAG_NO_PHYSICAL_CPU_OWNERSHIP |
		     FKI_X86_OFFLINE_FLAG_WAKE_RESET_UNDECIDED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL |
		     FKI_X86_OFFLINE_FLAG_REQUIRED_UNDESIGNED);
	expect_entry(FKI_X86_OFFLINE_WAKE_RESET_CONTROL,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_NO_PHYSICAL_CPU_OWNERSHIP |
		     FKI_X86_OFFLINE_FLAG_WAKE_RESET_UNDECIDED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_REONLINE_ROLLBACK_CONTROL,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_REONLINE_CONTROL_UNDECIDED |
		     FKI_X86_OFFLINE_FLAG_ROLLBACK_UNDESIGNED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_CONTROL_STATE_CR3_TRANSFER,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_NO_MEMORY_CONTROL_OWNERSHIP |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_NMI_INVARIANT,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_ASYNC_EVENT_UNSUPPORTED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_IRQ_INVARIANT,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_ASYNC_EVENT_UNSUPPORTED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_MACHINE_CHECK_INVARIANT,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_ASYNC_EVENT_UNSUPPORTED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_XNU_ENTRY,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_EXACTLY_ONCE_EXECUTOR,
		     FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL,
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL);
	expect_entry(FKI_X86_OFFLINE_REVERSE_ROLLBACK,
		     FKI_X86_OFFLINE_CLASS_REQUIRED_BUT_UNDESIGNED,
		     FKI_X86_OFFLINE_FLAG_ROLLBACK_UNDESIGNED |
		     FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL |
		     FKI_X86_OFFLINE_FLAG_REQUIRED_UNDESIGNED);

	assert(fki_x86_offline_obligation_lookup(FKI_X86_OFFLINE_OBLIGATION_COUNT,
						   &class, &flags) == -EINVAL);
	assert(fki_x86_offline_obligation_lookup(FKI_X86_OFFLINE_REMOVE_CPU_PRIMITIVE,
						   NULL, &flags) == -EINVAL);
	assert(fki_x86_offline_obligation_lookup(FKI_X86_OFFLINE_REMOVE_CPU_PRIMITIVE,
						   &class, NULL) == -EINVAL);

	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_UNRESOLVED_STRONGER_PROTOCOL, 0) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_REQUIRED_BUT_UNDESIGNED,
		FKI_X86_OFFLINE_FLAG_REQUIRES_STRONGER_PROTOCOL) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		primitive & ~FKI_X86_OFFLINE_FLAG_EXPORTED_SYMBOL_EVIDENCE) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		primitive & ~FKI_X86_OFFLINE_FLAG_NO_PHYSICAL_CPU_OWNERSHIP) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		primitive & ~FKI_X86_OFFLINE_FLAG_NO_MEMORY_CONTROL_OWNERSHIP) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_FORBIDDEN_AS_OWNERSHIP_CLAIM,
		claim | FKI_X86_OFFLINE_FLAG_EXPORTED_SYMBOL_EVIDENCE) == -EUCLEAN);
	assert(fki_x86_offline_obligation_validate_rules(
		FKI_X86_OFFLINE_CLASS_INSUFFICIENT_ALONE,
		primitive | (1U << 31)) == -EINVAL);
	assert(fki_x86_offline_obligation_validate_rules(~0U, 0) == -EINVAL);

	puts("x86 logical-offline proof-obligation fixtures passed");
	return 0;
}
